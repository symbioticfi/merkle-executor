#!/usr/bin/env python3
"""Reproduce selected protocol wire types from the checked-in JSON Schema subset."""
import json,pathlib,subprocess
root=pathlib.Path(__file__).resolve().parents[1]
schema=json.loads((root/'api/schemas/protocols.json').read_text())
def go_type(field):
    if field.get('x-go-type') == 'json.RawMessage':return 'json.RawMessage'
    if '$ref' in field:return field['$ref'].split('/')[-1]
    kind=field['type']
    if kind=='array':return '[]'+go_type(field['items'])
    return {'string':'string','integer':'int64','boolean':'bool'}[kind]
lines=['// Code generated by hack/generate-protocol-types.py; DO NOT EDIT.','// Source: api/schemas/protocols.json (manual upstream consumer subset).','package protocoltypes','']
if any(f.get('x-go-type') == 'json.RawMessage' for d in schema['$defs'].values() for f in d['properties'].values()):
    lines += ['import \"encoding/json\"', '']
for name,definition in schema['$defs'].items():
    lines.append('type '+name+' struct {')
    for wire,field in definition['properties'].items():
        lines.append('\t'+field['x-go-name']+' '+go_type(field)+' `json:"'+wire+(',omitempty' if field.get('x-go-omitempty') else '')+'"`')
    lines+=['}','']
out=root/'api/protocoltypes/types.gen.go'
out.write_text('\n'.join(lines))
subprocess.run(['gofmt','-w',str(out)],check=True)
